export function getEstate(slug) {
  return estates.find((e) => e.slug === slug);
}

export function pricedUnits(estate) {
  return estate.units.filter((u) => u.price);
}

export function fromPrice(estate) {
  const priced = pricedUnits(estate);
  if (!priced.length) return null;
  return Math.min(...priced.map((u) => u.price));
}

export function unitsLeft(estate) {
  return estate.units.reduce((n, u) => n + u.available, 0);
}

export function estateHref(estate) {
  return `/estates/${estate.slug}`;
}

export const deliveredHomes = estates.reduce((n, e) => n + (e.delivered || 0), 0);
